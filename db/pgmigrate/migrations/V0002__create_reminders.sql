CREATE TABLE
    IF NOT EXISTS reminders (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        task_id INTEGER REFERENCES tasks (id),
        title text NOT NULL CHECK (btrim (title) <> ''),
        description text,
        recurrence_type text NOT NULL DEFAULT 'once' CHECK (
            recurrence_type IN ('once', 'daily', 'weekly', 'monthly', 'yearly')
        ),
        timezone text NOT NULL,
        local_time time NOT NULL,
        start_date date NOT NULL,
        end_date date,
        -- Ближайший момент отправки.
        next_remind_at timestamptz NOT NULL,
        status text NOT NULL DEFAULT 'active' CHECK (
            status IN ('active', 'paused', 'completed', 'cancelled')
        ),
        created_at timestamptz NOT NULL DEFAULT now (),
        CHECK (
            end_date IS NULL
            OR end_date >= start_date
        )
    );

CREATE INDEX reminders_next_remind_idx ON reminders (next_remind_at)
WHERE
    status = 'active';